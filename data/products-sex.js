// Función para extraer categorías únicas
export const getCategories = () => {
  const categoriesSet = new Set()
  products.forEach(item => {
    const categorias = item.producto["Categorías"]
    if (categorias) {
      // Extraer categorías de la jerarquía (ej: "Geles y cosmética > Lubricantes")
      const hierarchy = categorias.split(' > ')
      hierarchy.forEach(cat => categoriesSet.add(cat))
      // También agregar la categoría completa
      categoriesSet.add(categorias)
    }
  })
  return ["Todos", ...Array.from(categoriesSet)]
}


