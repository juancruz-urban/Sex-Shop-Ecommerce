export const cleanPrice = (price) => {
  if (price === undefined || price === null) return 0
  
  if (typeof price === 'number') return price
  
  if (typeof price === 'string') {
    // Extraer solo números y punto decimal
    const match = price.match(/(\d+)(?:[.,](\d+))?/)
    if (!match) return 0
    
    const integerPart = match[1]
    const decimalPart = match[2] || ''
    
    // Convertir a número sin ningún tipo de multiplicación extra
    return parseInt(integerPart, 10)
  }
  
  return 0
}

// Versión manual si Intl.NumberFormat no funciona correctamente
export const formatPrice = (price) => {
  if (price === undefined || price === null) return "$0"
  
  let numericPrice = typeof price === 'number' ? price : cleanPrice(price)
  
  // Asegurar que es un número entero
  numericPrice = Math.round(numericPrice)
  
  // Formato manual: 22000 -> 22.000
  const formattedNumber = numericPrice.toLocaleString('es-AR', {
    minimumFractionDigits: 0,
    maximumFractionDigits: 0
  })
  console.log(formattedNumber)
  
  return `$${formattedNumber}`
}

